"""Current factual discourse prefixes never authorize mutations or drop edits."""
import pytest

from otravel.answering import readonly_question


@pytest.mark.parametrize('text',[
    'Теперь сколько взрослых и детей осталось? Первый номер сохранился прежним?',
    'теперь сколько взрослых и детей осталось? Первый номер сохранился прежним?',
    'Теперь тогда сколько взрослых и детей осталось? Первый номер сохранился прежним?',
    'Тогда теперь сколько взрослых и детей осталось? Первый номер сохранился прежним?',
    'Теперь какой бюджет сохранён? Ничего не меняй.',
    'Сейчас сколько взрослых и детей осталось? Первый номер сохранился прежним?',
    'Теперь сколько взрослых осталось? Бюджет остался прежним?',
    'Теперь сколько взрослых осталось? Если ребёнку будет десять лет, это что-то изменит?',
    'Теперь сколько взрослых осталось? «Бюджет 75000 рублей» — это цитата, ничего не меняй.',
])
def test_now_prefix_current_factual_question_enters_readonly_role(text):
    assert readonly_question(text)


@pytest.mark.parametrize('text',[
    'Теперь сколько взрослых осталось? Добавь ребёнка восьми лет.',
    'Теперь сколько взрослых осталось? Уменьши бюджет на 20000.',
    'Теперь сколько взрослых осталось? Можно изменить бюджет на 75000?',
    'Теперь сколько взрослых осталось? Подожди, я дополню.',
    'Теперь сколько взрослых осталось? Найди новые варианты.',
    'Теперь сколько взрослых осталось? Бюджет 75000 рублей.',
    'Теперь сколько взрослых осталось? Общий бюджет теперь 75000 рублей.',
    'Теперь сколько взрослых осталось? Ребёнку теперь десять лет.',
    'Сейчас сколько взрослых осталось? Бюджет 75000 рублей.',
    'Напомни состав. Ребёнку теперь десять лет.',
    'Бюджет 75000 рублей. Теперь сколько взрослых осталось?',
    'Ребёнку теперь десять лет. Теперь сколько взрослых осталось?',
    'Теперь сколько взрослых осталось? А ребёнку теперь десять лет.',
    'Теперь сколько взрослых осталось? И бюджет теперь 75000 рублей.',
])
def test_readonly_prefix_does_not_swallow_positive_edits_or_new_fact_clauses(text):
    assert not readonly_question(text)
